/*******************************************************************************
 * Lucide "heart" (U+E0F2), "radio" (U+E142) and "speaker" (U+E166), 28 px, 4 bpp.
 *
 * WHY THIS FILE EXISTS. LVGL's built-in symbol font has neither a heart nor a radio glyph, and
 * those are exactly the two the nav rail needs: Favorites and Radio. The design system specifies
 * Lucide throughout, so rather than settle for approximate stand-ins (LV_SYMBOL_LIST / _AUDIO,
 * which read as "list" and "now playing") this subsets the real thing.
 *
 * "speaker" replaced LV_SYMBOL_VOLUME_MAX on Rooms. That symbol read as VOLUME — a control this
 * rail does not have and which Now Playing already owns — whereas on a Sonos system a room simply
 * IS a speaker, which is the actual mental model.
 *
 * Generated, not hand-authored — regenerate rather than edit:
 *   npm install lucide-static
 *   npx lv_font_conv --font node_modules/lucide-static/font/lucide.ttf --size 28 --bpp 4 \
 *       --range '0xE0F2,0xE142,0xE166' --format lvgl --lv-include lvgl.h --no-compress \
 *       -o lv_font_lucide_28.c
 * Codepoints come from lucide-static/font/codepoints.json; they are PUA and NOT stable across
 * Lucide releases, so re-check them if the package is ever bumped.
 *
 * Three glyphs at 28 px cost ~8.5 KB of flash. Adding more sizes or icons means regenerating with a
 * wider --range; it is compiled only into UNIT_JUKEBOX, which is the only unit with this rail.
 *
 * Lucide is ISC licensed (https://lucide.dev) — see node_modules/lucide-static/LICENSE upstream.
 ******************************************************************************/

